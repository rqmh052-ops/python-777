"""Fail the build when R8 removed what Python calls on the Kotlin side.

Python (Chaquopy) calls RunCallback / PackageCallback methods by *name*.
If R8 renames the classes (RunCallback -> y0) or deletes the methods, every run
and every library install fails at runtime with
"'y0' object has no attribute 'emitState'". The names live in the APK's
classes*.dex string tables, so we can check for them right after the build.

Usage: python tools/verify_apk.py build/app/outputs/flutter-apk/app-release.apk
"""
from __future__ import annotations

import glob
import io
import os
import re
import subprocess
import sys
import zipfile
from pathlib import Path

REQUIRED = [
    "emitState",
    "emitPackage",
    "emitOutput",
    "emitInput",
    "emitExit",
    "emitError",
    "emitMissing",
    "requestInput",
    "shouldStop",
    "BayanPythonBridge$RunCallback",
    "BayanPythonBridge$PackageCallback",
    # البناء 2ب: الخدمة الأمامية وقناة النظام (المانيفست يشير إلى الخدمة بالاسم)
    "BayanScriptService",
    "BayanSystem",
]


def missing_names(apk: Path) -> list[str]:
    blobs: list[bytes] = []
    with zipfile.ZipFile(apk) as zf:
        for name in zf.namelist():
            if name.startswith("classes") and name.endswith(".dex"):
                blobs.append(zf.read(name))
    if not blobs:
        return list(REQUIRED)
    data = b"\0".join(blobs)
    return [name for name in REQUIRED if name.encode("utf-8") not in data]


def find_apksigner() -> str | None:
    roots = [os.environ.get("ANDROID_HOME"), os.environ.get("ANDROID_SDK_ROOT"), "/usr/local/lib/android/sdk"]
    for root in filter(None, roots):
        found = sorted(glob.glob(os.path.join(root, "build-tools", "*", "apksigner")))
        if found:
            return found[-1]
    return None


def check_signature(apk: Path) -> int:
    """المرحلة 3 (حارس CI): شهادة توقيع الـ APK يجب أن تطابق القيمة المحقونة في BYNUX_CERT_SHA256."""
    expected = os.environ.get("BYNUX_CERT_SHA256", "").strip().replace(":", "").lower()
    if not expected:
        print("SKIP signature guard: no BYNUX_CERT_SHA256 (debug signing, integrity check disabled in the app).")
        return 0
    tool = find_apksigner()
    if not tool:
        print("FAIL: apksigner not found, cannot verify the signing certificate.")
        return 1
    out = subprocess.run([tool, "verify", "--print-certs", str(apk)], capture_output=True, text=True)
    if out.returncode != 0:
        print("FAIL: apksigner verify failed:\n" + out.stdout + out.stderr)
        return 1
    digests = re.findall(r"certificate SHA-256 digest: ([0-9a-fA-F]{64})", out.stdout)
    if not digests or any(d.lower() != expected for d in digests):
        print(f"FAIL: APK certificate {digests} != injected {expected}. The app would reject itself.")
        return 1
    print("OK: APK signing certificate matches the injected SHA-256 (" + expected[:16] + "...)")
    return 0


def check_cython(apk: Path) -> int:
    """المرحلة 4: لا مصدر bayan_runtime داخل أرشيفات Chaquopy، ويوجد الـ .so المتوقع."""
    if os.environ.get("BYNUX_EXPECT_CYTHON", "") != "1":
        return 0
    bad: list[str] = []
    has_so = False
    with zipfile.ZipFile(apk) as zf:
        for name in zf.namelist():
            if re.search(r"bayan_runtime.*\.so$", name):
                has_so = True
            if name.startswith("assets/chaquopy/") and name.endswith((".imy", ".zip")):
                try:
                    inner = zipfile.ZipFile(io.BytesIO(zf.read(name)))
                except zipfile.BadZipFile:
                    continue
                for member in inner.namelist():
                    base = member.rsplit("/", 1)[-1]
                    if base == "bayan_runtime.py" or re.fullmatch(r"bayan_runtime.*\.pyc", base):
                        bad.append(f"{name}:{member}")
                    if re.search(r"bayan_runtime.*\.so$", member):
                        has_so = True
    if bad:
        print("FAIL: Python source/bytecode of bayan_runtime is still inside the APK:\n  " + "\n  ".join(bad))
        return 1
    if not has_so:
        print("FAIL: expected a compiled bayan_runtime*.so in the APK but none was found.")
        return 1
    print("OK: bayan_runtime ships as a compiled .so (no .py/.pyc in Chaquopy archives)")
    return 0


def main() -> int:
    if len(sys.argv) != 2:
        print("usage: verify_apk.py <app-release.apk>")
        return 2
    apk = Path(sys.argv[1])
    if not apk.is_file():
        print(f"APK not found: {apk}")
        return 2
    missing = missing_names(apk)
    if missing:
        print("FAIL: these names are missing from the APK (R8 removed or renamed them):")
        for name in missing:
            print(f"  - {name}")
        print("The app would show: AttributeError: 'y0' object has no attribute 'emitState'.")
        print(
            "Check android/app/proguard-rules.pro (generated by tools/prepare_android.py) is present, "
            "or re-run this workflow with the 'shrink' input set to false as a quick rollback."
        )
        return 1
    print(f"OK: all {len(REQUIRED)} Kotlin callback names survived in {apk.name}")
    rc = check_signature(apk)
    rc = check_cython(apk) or rc
    return rc


if __name__ == "__main__":
    raise SystemExit(main())
