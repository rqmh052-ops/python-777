// طابقها يدويًا مع المصادر الرسمية (letsencrypt.org/certificates وpki.goog/repository) عند التحديث.

import 'dart:io';

/// المضيف الوحيد المسموح به.
const String pinnedHost = 'bayan-storage-api.aaro3498.workers.dev';

/// رسالة تظهر داخل ميزات السحابة فقط عند فشل التحقق من الشهادة.
const String pinnedTlsFailureMessage =
    'تعذّر التحقق من أمان الاتصال بالسحابة. قد تكون الشبكة تعترض الاتصال أو أن '
    'شهادة الخادم تغيّرت. تشغيل السكربتات وتثبيت المكتبات غير متأثرَين.';

class PinnedConnectionException implements Exception {
  const PinnedConnectionException(this.message);
  final String message;
  @override
  String toString() => message;
}

/// يتحقق أن العنوان https وعلى المضيف المسموح فقط، وإلا يرمي.
Uri requirePinnedUri(Uri uri) {
  if (uri.scheme != 'https') {
    throw ArgumentError('مسموح https فقط: $uri');
  }
  if (uri.host.toLowerCase() != pinnedHost) {
    throw ArgumentError('مضيف غير مسموح: ${uri.host}');
  }
  return uri;
}

SecurityContext? _context;

/// السياق المثبَّت: لا جذور نظام، فقط القائمة أدناه.
SecurityContext buildPinnedContext() {
  final existing = _context;
  if (existing != null) return existing;
  final ctx = SecurityContext(withTrustedRoots: false);
  for (final entry in pinnedRootPems) {
    ctx.setTrustedCertificatesBytes(entry.codeUnits);
  }
  return _context = ctx;
}

/// HttpClient مبني على السياق المثبَّت، ويرفض أي شهادة فاشلة.
HttpClient createPinnedHttpClient({
  Duration connectionTimeout = const Duration(seconds: 20),
  Duration idleTimeout = const Duration(seconds: 20),
  SecurityContext? contextOverride,
}) {
  final client = HttpClient(context: contextOverride ?? buildPinnedContext())
    ..connectionTimeout = connectionTimeout
    ..idleTimeout = idleTimeout
    ..badCertificateCallback = (X509Certificate cert, String host, int port) => false;
  return client;
}

/// يفتح طلبًا (أي طريقة) بعد فرض https والمضيف، ويحوّل أخطاء TLS لرسالة عربية.
Future<HttpClientRequest> openPinned(
  HttpClient client,
  String method,
  Uri uri, {
  Duration timeout = const Duration(seconds: 25),
}) async {
  requirePinnedUri(uri);
  try {
    return await client.openUrl(method, uri).timeout(timeout);
  } on HandshakeException {
    throw const PinnedConnectionException(pinnedTlsFailureMessage);
  } on TlsException {
    throw const PinnedConnectionException(pinnedTlsFailureMessage);
  }
}

Future<HttpClientRequest> pinnedGet(HttpClient c, Uri u) => openPinned(c, 'GET', u);
Future<HttpClientRequest> pinnedPost(HttpClient c, Uri u) => openPinned(c, 'POST', u);
Future<HttpClientRequest> pinnedPut(HttpClient c, Uri u) => openPinned(c, 'PUT', u);
Future<HttpClientRequest> pinnedDelete(HttpClient c, Uri u) => openPinned(c, 'DELETE', u);

